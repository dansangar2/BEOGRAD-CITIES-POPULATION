"""Build the existing web bundles from ordered sources, using only Python."""
from __future__ import annotations

import argparse
import json
from pathlib import Path


STATIC_ROOT = Path(__file__).resolve().parents[1] / "ciudades_del_mundo/static/ciudades_del_mundo"
SOURCE_ROOT = STATIC_ROOT / "src"
HEADER = "/* Generated by tools/build_web_assets.py; edit src/ instead. */\n"


def render_bundles(source_root: Path = SOURCE_ROOT) -> dict[str, str]:
    manifest = json.loads((source_root / "manifest.json").read_text(encoding="utf-8"))
    if set(manifest) != {"app.js", "app.css"}:
        raise ValueError("The manifest must declare app.js and app.css.")
    bundles = {}
    for bundle, sources in manifest.items():
        if not isinstance(sources, list) or not sources:
            raise ValueError(f"Invalid bundle: {bundle}")
        parts = []
        for name in sources:
            path = (source_root / name).resolve()
            if not path.is_relative_to(source_root.resolve()):
                raise ValueError(f"Source outside src/: {name}")
            parts.append(path.read_text(encoding="utf-8"))
        bundles[bundle] = HEADER + "".join(parts)
    return bundles


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true", help="Verify bundles without writing them.")
    args = parser.parse_args()
    stale = []
    for name, content in render_bundles().items():
        destination = STATIC_ROOT / name
        if args.check:
            if not destination.exists() or destination.read_text(encoding="utf-8") != content:
                stale.append(name)
        else:
            destination.write_text(content, encoding="utf-8", newline="\n")
    if stale:
        print("Stale bundles: " + ", ".join(stale))
        return 1
    print("Web bundles verified." if args.check else "Web bundles built.")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
