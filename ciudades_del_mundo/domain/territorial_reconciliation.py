"""Versioned territorial references and evidence-backed reconciliation plans.

References are supplied and reviewed by people, never generated by the proposer.
Source identities are page/row identities; QIDs are attributes, not row keys.
"""
from __future__ import annotations

from dataclasses import dataclass, replace
import re
import unicodedata

from ciudades_del_mundo.domain.admin_area import ScrapedAdminArea


SCHEMA_VERSION = 1
ENGINE_VERSION = "territorial-v1"


class ReconciliationError(ValueError):
    """A concrete input, proposal or concurrency problem; no partial apply."""


@dataclass(frozen=True)
class TerritorialRole:
    id: str
    level: int


@dataclass(frozen=True)
class ReferenceEntity:
    id: str
    code: str
    names: tuple[str, ...]
    role: str
    parent: str | None
    qid: str = ""
    repeat_of: str | None = None


@dataclass(frozen=True)
class TerritorialReference:
    country: str
    version: str
    provenance: str
    scope: str
    entry_path: str
    roles: tuple[TerritorialRole, ...]
    entities: tuple[ReferenceEntity, ...]
    exceptions: tuple[dict, ...]
    exclusions: tuple[dict, ...] = ()


@dataclass(frozen=True)
class EvidenceRow:
    id: str
    page: str
    block: str
    entity: ScrapedAdminArea


@dataclass(frozen=True)
class PlanNode:
    reference_id: str
    evidence_ids: tuple[str, ...]
    role: str
    level: int
    parent: str | None
    reason: str
    reference_ids: tuple[str, ...]


@dataclass(frozen=True)
class TerritorialPlan:
    schema_version: int
    country: str
    reference_version: str
    evidence_version: str
    nodes: tuple[PlanNode, ...]
    unresolved: tuple[dict, ...]
    discrepancies: tuple[dict, ...]
    excluded: tuple[dict, ...] = ()


def normalized_name(value: str) -> str:
    return " ".join(unicodedata.normalize("NFKC", value).casefold().split())


def _text(value, field: str, *, maximum: int = 500) -> str:
    if not isinstance(value, str) or not value.strip() or len(value) > maximum:
        raise ReconciliationError(f"{field}: expected nonempty text (max {maximum}).")
    return value


def _identifier(value, field: str, *, maximum: int = 64) -> str:
    value = _text(value, field, maximum=maximum)
    if not re.fullmatch(r"[A-Za-z0-9_.:-]+", value):
        raise ReconciliationError(f"{field}: invalid identifier {value!r}.")
    return value


def _objects(value, field: str) -> list[dict]:
    if not isinstance(value, list) or any(not isinstance(item, dict) for item in value):
        raise ReconciliationError(f"{field}: expected an array of objects.")
    return value


def _strings(value, field: str) -> tuple[str, ...]:
    if not isinstance(value, list) or not value or any(not isinstance(v, str) or not v for v in value):
        raise ReconciliationError(f"{field}: expected a nonempty array of strings.")
    if len(set(value)) != len(value):
        raise ReconciliationError(f"{field}: duplicate identifiers.")
    return tuple(value)


def parse_reference(data: dict) -> TerritorialReference:
    if not isinstance(data, dict) or type(data.get("schema_version")) is not int or data["schema_version"] != 1:
        raise ReconciliationError("reference.schema_version: expected 1.")
    required = {"schema_version", "country", "version", "provenance", "scope", "entry_path", "roles", "entities", "exceptions"}
    if not required <= set(data) or set(data) - required - {"exclusions"}:
        raise ReconciliationError("reference: unexpected or missing version 1 schema fields.")
    country = _identifier(data.get("country"), "reference.country")
    roles = []
    for item in _objects(data.get("roles"), "reference.roles"):
        if set(item) != {"id", "level"}:
            raise ReconciliationError("reference.role: expected id and level.")
        level = item.get("level")
        if type(level) is not int or not 0 <= level <= 5:
            raise ReconciliationError("reference.roles.level: expected integer 0..5.")
        roles.append(TerritorialRole(_identifier(item.get("id"), "role.id"), level))
    if not roles or sorted(r.level for r in roles) != list(range(len(roles))) or len({r.id for r in roles}) != len(roles):
        raise ReconciliationError("reference.roles: unique roles at consecutive levels starting at 0 required.")
    role_map = {r.id: r.level for r in roles}
    entities = []
    for item in _objects(data.get("entities"), "reference.entities"):
        if not {"id", "code", "names", "role", "parent"} <= set(item) or set(item) - {"id", "code", "names", "role", "parent", "qid", "repeat_of"}:
            raise ReconciliationError("reference.entity: unexpected or missing fields.")
        role = _identifier(item.get("role"), "entity.role")
        if role not in role_map:
            raise ReconciliationError(f"reference.entity {item.get('id')}: unknown role {role}.")
        qid = item.get("qid", "")
        if not isinstance(qid, str) or (qid and not re.fullmatch(r"Q[1-9][0-9]*", qid)):
            raise ReconciliationError("reference.entity.qid: invalid QID.")
        entities.append(ReferenceEntity(
            _identifier(item.get("id"), "entity.id"), _identifier(item.get("code"), "entity.code"),
            _strings(item.get("names"), "entity.names"), role, item.get("parent"), qid, item.get("repeat_of"),
        ))
    by_id = {e.id: e for e in entities}
    if not entities or len(by_id) != len(entities) or len({e.code for e in entities}) != len(entities):
        raise ReconciliationError("reference.entities: unique IDs/codes and nonempty coverage required.")
    roots = []
    exceptions = _objects(data.get("exceptions"), "reference.exceptions")
    exception_entities = set()
    exception_ids = set()
    for item in exceptions:
        if set(item) != {"id", "entities", "reason", "provenance"}:
            raise ReconciliationError("reference.exception: expected id, entities, reason and provenance.")
        key = _identifier(item.get("id"), "exception.id")
        if key in exception_ids or key in by_id or key in role_map:
            raise ReconciliationError(f"reference.exception: duplicate reference ID {key}.")
        exception_ids.add(key)
        _text(item.get("reason"), "exception.reason", maximum=4000)
        _text(item.get("provenance"), "exception.provenance", maximum=2000)
        ids = _strings(item.get("entities"), "exception.entities")
        if set(ids) - by_id.keys():
            raise ReconciliationError(f"reference.exception {key}: unknown entities.")
        exception_entities.update(ids)
    if set(by_id) & set(role_map):
        raise ReconciliationError("reference: entity and role IDs must be disjoint.")
    exclusions = _objects(data.get("exclusions", []), "reference.exclusions")
    exclusion_ids = set()
    for item in exclusions:
        if set(item) != {"id", "source_codes", "names", "reason", "provenance"}:
            raise ReconciliationError("reference.exclusion: expected id, source_codes, names, reason and provenance.")
        key = _identifier(item["id"], "exclusion.id")
        if key in exclusion_ids or key in by_id or key in role_map or key in exception_ids:
            raise ReconciliationError(f"reference.exclusion: duplicate reference ID {key}.")
        exclusion_ids.add(key)
        for code in _strings(item["source_codes"], "exclusion.source_codes"):
            _identifier(code, "exclusion.source_codes")
        _strings(item["names"], "exclusion.names")
        _text(item["reason"], "exclusion.reason", maximum=4000)
        _text(item["provenance"], "exclusion.provenance", maximum=2000)
    for entity in entities:
        if len(country) + 1 + len(entity.code) > 128:
            raise ReconciliationError(f"reference {entity.id}: canonical persisted ID exceeds 128 characters.")
        level = role_map[entity.role]
        if level == 0:
            roots.append(entity.id)
            if entity.parent is not None:
                raise ReconciliationError(f"reference {entity.id}: root must not have a parent.")
        else:
            if not isinstance(entity.parent, str) or entity.parent not in by_id or role_map[by_id[entity.parent].role] != level - 1:
                raise ReconciliationError(f"reference {entity.id}: missing parent at level {level - 1} (or cycle).")
        if entity.repeat_of is not None:
            if entity.repeat_of != entity.parent or entity.id not in exception_entities:
                raise ReconciliationError(f"reference {entity.id}: repetition requires its consecutive parent and a sourced exception.")
    if len(roots) != 1:
        raise ReconciliationError("reference: exactly one country root required.")
    path = _text(data.get("entry_path"), "reference.entry_path", maximum=128)
    if not re.fullmatch(r"[a-z0-9_-]+/", path):
        raise ReconciliationError("reference.entry_path: expected a CityPopulation country slug followed by /.")
    return TerritorialReference(country, _text(data.get("version"), "reference.version", maximum=100),
        _text(data.get("provenance"), "reference.provenance", maximum=4000),
        _text(data.get("scope"), "reference.scope", maximum=2000), path,
        tuple(roles), tuple(entities), tuple(exceptions), tuple(exclusions))


def parse_plan(data: dict) -> TerritorialPlan:
    fields = {"schema_version", "country", "reference_version", "evidence_version", "nodes", "unresolved", "discrepancies"}
    if not isinstance(data, dict) or not fields <= set(data) or set(data) - fields - {"excluded"} or type(data.get("schema_version")) is not int or data["schema_version"] != 1:
        raise ReconciliationError("plan: expected exactly the version 1 schema fields.")
    nodes = []
    for item in _objects(data["nodes"], "plan.nodes"):
        if set(item) != {"reference_id", "evidence_ids", "role", "level", "parent", "reason", "reference_ids"}:
            raise ReconciliationError("plan.node: unexpected/missing fields; metrics, code and URLs cannot be proposed.")
        if type(item["level"]) is not int or not 0 <= item["level"] <= 5:
            raise ReconciliationError("plan.node.level: expected integer 0..5.")
        if item["parent"] is not None and not isinstance(item["parent"], str):
            raise ReconciliationError("plan.node.parent: expected reference ID or null.")
        nodes.append(PlanNode(_identifier(item["reference_id"], "node.reference_id"),
            _strings(item["evidence_ids"], "node.evidence_ids"), _identifier(item["role"], "node.role"),
            item["level"], item["parent"], _text(item["reason"], "node.reason", maximum=4000),
            _strings(item["reference_ids"], "node.reference_ids")))
    for field in ("unresolved", "discrepancies"):
        for issue in _objects(data[field], f"plan.{field}"):
            if set(issue) != {"id", "reason"}:
                raise ReconciliationError(f"plan.{field}: expected id and reason.")
            _text(issue["id"], "issue.id")
            _text(issue["reason"], "issue.reason", maximum=4000)
    excluded = _objects(data.get("excluded", []), "plan.excluded")
    for item in excluded:
        if set(item) != {"evidence_id", "reference_id", "reason"}:
            raise ReconciliationError("plan.excluded: expected evidence_id, reference_id and reason.")
        _text(item["evidence_id"], "excluded.evidence_id")
        _identifier(item["reference_id"], "excluded.reference_id")
        _text(item["reason"], "excluded.reason", maximum=4000)
    return TerritorialPlan(1, _identifier(data["country"], "plan.country"),
        _text(data["reference_version"], "plan.reference_version", maximum=100),
        _text(data["evidence_version"], "plan.evidence_version", maximum=100), tuple(nodes),
        tuple(data["unresolved"]), tuple(data["discrepancies"]), tuple(excluded))


def validate_plan(plan: TerritorialPlan, reference: TerritorialReference,
                  evidence: tuple[EvidenceRow, ...], evidence_version: str) -> list[ScrapedAdminArea]:
    """Compile only explicit, fully covered, evidence-backed relationships.

    No fuzzy name/QID deduplication: distinct source codes stay distinct. Reusing
    a source row across consecutive levels requires a reference exception.
    """
    if (plan.country, plan.reference_version, plan.evidence_version) != (reference.country, reference.version, evidence_version):
        raise ReconciliationError("plan: input country/reference/evidence versions differ.")
    if plan.unresolved or plan.discrepancies:
        raise ReconciliationError(f"plan: unresolved={list(plan.unresolved)}, discrepancies={list(plan.discrepancies)}.")
    refs = {e.id: e for e in reference.entities}
    roles = {r.id: r.level for r in reference.roles}
    rows = {r.id: r for r in evidence}
    if not rows or len(rows) != len(evidence) or any(r.entity.country_code != reference.country for r in evidence):
        raise ReconciliationError("evidence: empty, duplicate IDs or foreign country.")
    nodes = {n.reference_id: n for n in plan.nodes}
    if len(nodes) != len(plan.nodes) or set(nodes) != set(refs):
        raise ReconciliationError(f"plan.coverage: missing={sorted(set(refs)-set(nodes))}, extra={sorted(set(nodes)-set(refs))}, or duplicate nodes.")
    citations = set(refs) | set(roles) | {e["id"] for e in reference.exceptions} | {e["id"] for e in reference.exclusions}
    used: dict[str, list[str]] = {}
    code_owners: dict[str, list[str]] = {}
    result = []
    for key, node in nodes.items():
        ref = refs[key]
        if (node.role, node.level, node.parent) != (ref.role, roles[ref.role], ref.parent):
            raise ReconciliationError(f"plan {key}: role/level/parent disagrees with reference (cycle or territorial mismatch).")
        if key not in node.reference_ids or set(node.reference_ids) - citations:
            raise ReconciliationError(f"plan {key}: missing own reference or unknown citations.")
        if ref.repeat_of and not any(e["id"] in node.reference_ids and key in e["entities"] for e in reference.exceptions):
            raise ReconciliationError(f"plan {key}: missing sourced repetition exception citation.")
        if set(node.evidence_ids) - rows.keys():
            raise ReconciliationError(f"plan {key}: unknown evidence {sorted(set(node.evidence_ids)-rows.keys())}.")
        sources = [rows[r].entity for r in node.evidence_ids]
        limits = {"name": 255, "code": 64, "entity_type": 80, "raw_entity_type": 80, "data_wd": 40, "url": 500}
        for source in sources:
            if any(getattr(source, field) is not None and len(str(getattr(source, field))) > maximum for field, maximum in limits.items()):
                raise ReconciliationError(f"plan {key}: source values exceed persisted field limits.")
        names = {normalized_name(n) for n in ref.names}
        if any(normalized_name(s.name) not in names or (ref.qid and s.data_wd != ref.qid) for s in sources):
            raise ReconciliationError(f"plan {key}: source name/QID does not match reference aliases.")
        # The existing parser uses the country slug as a context-only root code
        # when an infosection has no source ID. Such a context is identified by
        # its page/row and verified name, never by that fallback slug alone.
        identified_sources = [rows[r] for r in node.evidence_ids if not (
            rows[r].entity.code == reference.country and rows[r].entity.level == 0
            and "infosection" in rows[r].block)]
        if len({r.entity.code for r in identified_sources}) > 1:
            raise ReconciliationError(f"plan {key}: cannot collapse distinct source rows/codes by name or QID.")
        allowed_codes = {ref.code}
        ancestor = ref
        while ancestor.repeat_of:
            ancestor = refs[ancestor.repeat_of]
            allowed_codes.add(ancestor.code)
        if {r.entity.code for r in identified_sources} - allowed_codes:
            raise ReconciliationError(f"plan {key}: source identifier does not match the reviewed reference identity/repetition.")
        if len({s.data_wd for s in sources if s.data_wd}) > 1:
            raise ReconciliationError(f"plan {key}: conflicting observed QIDs.")
        for row_id in node.evidence_ids:
            used.setdefault(row_id, []).append(key)
        for row in identified_sources:
            code_owners.setdefault(row.entity.code, []).append(key)
        # First citation explicitly selects the metric observation; every value
        # comes from that row. The model cannot manufacture names or metrics.
        source = sources[0]
        result.append(replace(source, code=ref.code, level=node.level,
            raw_entity_type=source.raw_entity_type or source.entity_type,
            parent_code=refs[ref.parent].code if ref.parent else None,
            preserve_source_code=True))
    exclusions = {e["id"]: e for e in reference.exclusions}
    excluded_ids = set()
    for item in plan.excluded:
        row_id, reference_id = item["evidence_id"], item["reference_id"]
        if row_id not in rows or reference_id not in exclusions or row_id in excluded_ids or row_id in used:
            raise ReconciliationError(f"plan.excluded {row_id}: unknown, duplicate or also mapped evidence/reference.")
        source = rows[row_id].entity
        rule = exclusions[reference_id]
        if source.code not in rule["source_codes"] or normalized_name(source.name) not in {normalized_name(n) for n in rule["names"]}:
            raise ReconciliationError(f"plan.excluded {row_id}: source identity differs from the reviewed exclusion.")
        excluded_ids.add(row_id)
    missing = set(rows) - set(used) - excluded_ids
    if missing:
        raise ReconciliationError(f"plan.evidence_coverage: unaccounted rows {sorted(missing)}.")
    by_page_code = {}
    for row in evidence:
        by_page_code.setdefault((row.page, row.entity.code), []).append(row.id)
    for key, node in nodes.items():
        ancestors = {key}
        parent = refs[key].parent
        while parent:
            ancestors.add(parent)
            parent = refs[parent].parent
        for row_id in node.evidence_ids:
            row = rows[row_id]
            observed_parents = [p for p in by_page_code.get((row.page, row.entity.parent_code), ()) if p not in excluded_ids]
            if observed_parents and not any(set(used[p]) & ancestors for p in observed_parents):
                raise ReconciliationError(f"plan {key}: observed parent of evidence {row_id} contradicts the reference branch.")
            if not observed_parents and row.entity.parent_code in code_owners and not set(code_owners[row.entity.parent_code]) & ancestors:
                raise ReconciliationError(f"plan {key}: cross-page observed parent of evidence {row_id} contradicts the reference branch.")
    for owner_ids in [*used.values(), *code_owners.values()]:
        unique = sorted(set(owner_ids), key=lambda key: roles[refs[key].role])
        for previous, current in zip(unique, unique[1:]):
            if refs[current].repeat_of != previous:
                raise ReconciliationError(f"plan {current}: source reused without consecutive reference repetition after {previous}.")
    return sorted(result, key=lambda e: (e.level, e.code))
