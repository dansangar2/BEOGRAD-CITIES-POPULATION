def normalize_language_code(language_code: str | None) -> str:
    """Normalize Django language codes while preserving Serbian Latin."""

    value = str(language_code or "").strip().lower().replace("_", "-")
    if value.startswith("sr-latn"):
        return "sr-latn"
    return value.split("-", 1)[0] if value else ""


def spain_name(name: str, language_code: str | None) -> str:
    """Return the localized display name for a Spain-specific geography label."""

    value = str(name or "").strip()
    labels = SPAIN_NAME_LABELS.get(normalize_language_code(language_code), {})
    return labels.get(value, value)


